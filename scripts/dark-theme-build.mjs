// Builds src/app/dark-theme.css (Help C8, UX 36): the dashboard's dark
// theme as a remap of Tailwind v4's colour variables, scoped by
// data-theme on the dashboard root ("dark", or "auto" + the system
// setting). Light steps swap with dark ones (50↔950 … 300↔700) and
// 400–600 stay, so filled buttons (bg-teal-600 + white text) don't change;
// text in a 600 shade gets its 400 for contrast on dark surfaces. "white"
// becomes the card surface. A data-theme="light" scope inside (the print
// views) re-declares the light values. Flat selectors only (no nesting).
// Run: node scripts/dark-theme-build.mjs
import fs from "node:fs";

const theme = fs.readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const globals = fs.readFileSync("src/app/globals.css", "utf8");
const FAMILIES = ["slate", "gray", "teal", "red", "amber", "green", "orange", "blue", "violet", "emerald", "yellow", "sky", "rose", "purple", "indigo"];
const STEPS = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];
const SWAP = { 50: "950", 100: "900", 200: "800", 300: "700", 700: "300", 800: "200", 900: "100", 950: "50" };
// Neutral text (slate/gray 500–600) is body copy: on a dark card it needs
// lighter steps than a straight swap gives (>= 4.5:1, WCAG AA).
const NEUTRAL_SWAP = { ...SWAP, 400: "500", 500: "400", 600: "300" };
const NEUTRAL = new Set(["slate", "gray"]);

const value = (fam, step) => {
  const re = new RegExp(`--color-${fam}-${step}:\s*([^;]+);`);
  return (globals.match(re) ?? theme.match(re))?.[1].trim();
};
const light = [];
const dark = [];
for (const fam of FAMILIES) {
  for (const step of STEPS) {
    const v = value(fam, step);
    if (!v) throw new Error(`no ${fam}-${step}`);
    light.push(`  --color-${fam}-${step}: ${v};`);
    const swap = NEUTRAL.has(fam) ? NEUTRAL_SWAP : SWAP;
    if (swap[step]) dark.push(`  --color-${fam}-${step}: ${value(fam, swap[step])};`);
  }
}
const surface = value("slate", "900");
const darkVars = (indent) =>
  [...dark, `  --color-white: ${surface};`, "  color-scheme: dark;", "  color: var(--color-slate-900);"].map((l) => indent + l).join("\n");
const accents = FAMILIES.filter((f) => f !== "slate" && f !== "gray");
// White text stays white (the variable is the surface now); 600-shade text
// gets its 400 for contrast. Never inside a light scope.
const fixes = (scope, indent) =>
  [
    `${indent}${scope} .text-white { color: #fff; }`,
    ...accents.map((f) => `${indent}${scope} .text-${f}-600:not([data-theme="light"] *) { color: var(--color-${f}-400); }`),
  ].join("\n");

const css = `/* GENERATED by scripts/dark-theme-build.mjs — do not edit by hand. */
/* The dashboard's dark theme (Help C8): see the script for the rules. */

[data-theme="dark"] {
${darkVars("")}
}
${fixes('[data-theme="dark"]', "")}

@media (prefers-color-scheme: dark) {
  [data-theme="auto"] {
${darkVars("  ")}
  }
${fixes('[data-theme="auto"]', "  ")}
}

/* Print views and anything else that must stay light. */
[data-theme="light"] {
${light.join("\n")}
  --color-white: #fff;
  color-scheme: light;
}
`;
fs.writeFileSync("src/app/dark-theme.css", css);
console.log(`dark-theme.css: ${dark.length} swapped, ${light.length} light`);
